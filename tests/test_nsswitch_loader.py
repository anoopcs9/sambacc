def test_find(tmp_path):
    nss_file = tmp_path / "nsswitch.conf"
    nss_file.write_text(nsswitch1)
    nss = sambacc.nsswitch_loader.find(paths=[str(nss_file)])
    assert nss.winbind_enabled() is False
    assert len(nss.lines) == 3


def test_find_first_path(tmp_path):
    nss_file = tmp_path / "nsswitch.conf"
    nss_file.write_text(nsswitch1)
    nonexistent = tmp_path / "does_not_exist"
    nss = sambacc.nsswitch_loader.find(paths=[str(nonexistent), str(nss_file)])
    assert len(nss.lines) == 3


def test_find_not_found(tmp_path):
    fake1 = tmp_path / "fake1"
    fake2 = tmp_path / "fake2"
    with pytest.raises(FileNotFoundError):
        sambacc.nsswitch_loader.find(paths=[str(fake1), str(fake2)])


def test_read_write_file(tmp_path):
    nss_file = tmp_path / "nsswitch.conf"
    nss_file.write_text(nsswitch1)
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader(str(nss_file))
    nss.read()
    nss.ensure_winbind_enabled()
    nss.write()
    content = nss_file.read_text()
    assert "passwd:    files winbind" in content
    assert "group:    files winbind" in content
