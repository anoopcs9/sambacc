import io

import pytest

import sambacc.nsswitch_loader

nsswitch1 = """\
# /etc/nsswitch.conf

passwd:    files
group:     files
hosts:     files dns
"""

nsswitch_winbind = """\
# /etc/nsswitch.conf

passwd:    files winbind
group:    files winbind
hosts:     files dns
"""

nsswitch_altfiles = """\
# /etc/nsswitch.conf

passwd:    files altfiles
group:    files altfiles
hosts:     files dns
"""


def test_loadlines():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch1.splitlines(True))
    assert len(nss.lines) == 3
    assert "passwd" in nss.idx
    assert "group" in nss.idx


def test_loadlines_skips_comments_and_blanks():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch1.splitlines(True))
    for line in nss.lines:
        assert not line.startswith("#")
        assert line.strip()


def test_dumplines():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch1.splitlines(True))
    output = "".join(nss.dumplines())
    assert output.startswith("# Generated by sambacc")
    assert "passwd:" in output
    assert "group:" in output
    assert "hosts:" in output


def test_readfp_writefp_roundtrip():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.readfp(io.StringIO(nsswitch1))
    fh = io.StringIO()
    nss.writefp(fh)
    output = fh.getvalue()
    assert "passwd:    files\n" in output
    assert "group:     files\n" in output
    assert "hosts:     files dns\n" in output


def test_winbind_enabled_false():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch1.splitlines(True))
    assert not nss.winbind_enabled()


def test_winbind_enabled_true():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch_winbind.splitlines(True))
    assert nss.winbind_enabled()


def test_ensure_winbind_enabled():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch1.splitlines(True))
    nss.ensure_winbind_enabled()
    assert nss.winbind_enabled()
    fh = io.StringIO()
    nss.writefp(fh)
    output = fh.getvalue()
    assert "passwd:    files winbind\n" in output
    assert "group:    files winbind\n" in output


def test_ensure_winbind_enabled_idempotent():
    nss = sambacc.nsswitch_loader.NameServiceSwitchLoader("")
    nss.loadlines(nsswitch_winbind.splitlines(True))
    nss.ensure_winbind_enabled()
    assert nss.winbind_enabled()
    assert len(nss.lines) == 3


